export function getNearestKeyDistrict(lat: number, lng: number): { district: string; state: string; distanceKm: number } {
  let closest = { district: 'Palghar', state: 'Maharashtra', distanceKm: Infinity };

  for (const [district, info] of Object.entries(INDIA_KEY_DISTRICT_CENTROIDS)) {
    // Euclidean approximation for fast distance comparison
    const dLat = (lat - info.lat) * 111;
    const dLng = (lng - info.lng) * 111 * Math.cos((lat * Math.PI) / 180);
    const dist = Math.sqrt(dLat * dLat + dLng * dLng);
    if (dist < closest.distanceKm) {
      closest = { district, state: info.state, distanceKm: dist };
    }
  }

  return closest;
}

